export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** Blank columns between glyphs, in cube units. */
export const GLYPH_GAP = 1;

export type Cube = { x: number; y: number };

/**
 * Lay a string out into unit cube coordinates. Origin is the centre of the
 * word, x grows right, y grows up — caller scales and positions the result.
 */
export function layoutText(text: string): { cubes: Cube[]; width: number; height: number } {
  const chars = text.toUpperCase().split("");
  const width = chars.length * GLYPH_W + Math.max(0, chars.length - 1) * GLYPH_GAP;
  const cubes: Cube[] = [];

  chars.forEach((char, index) => {
    const rows = (GLYPHS[char] ?? GLYPHS["?"]).split(" ");
    const originX = index * (GLYPH_W + GLYPH_GAP);

    rows.forEach((row, rowIndex) => {
      for (let col = 0; col < GLYPH_W; col += 1) {
        if (row[col] !== "1") continue;
        cubes.push({
          x: originX + col - (width - 1) / 2,
          y: GLYPH_H - 1 - rowIndex - (GLYPH_H - 1) / 2,
        });
      }
    });
  });

  return { cubes, width, height: GLYPH_H };
}
